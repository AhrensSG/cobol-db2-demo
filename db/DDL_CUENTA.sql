CREATE TABLE CUENTA (
    NUM_CUENTA    VARCHAR(20)  NOT NULL,
    TITULAR       VARCHAR(60)  NOT NULL,
    SALDO         DECIMAL(15,2) NOT NULL DEFAULT 0,
    DIVISA        CHAR(3)      NOT NULL DEFAULT 'EUR',
    ESTADO        CHAR(1)      NOT NULL DEFAULT 'A',
    FECHA_ALTA    CHAR(8)      NOT NULL,
    PRIMARY KEY (NUM_CUENTA)
);

CREATE INDEX CUENTA_TITULAR_IDX
    ON CUENTA (TITULAR);

